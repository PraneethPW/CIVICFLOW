import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync, chmodSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";
const root = fileURLToPath(new URL("../", import.meta.url));
const [target = "local", action = "sync"] = process.argv.slice(2);
if (
  !["local", "production"].includes(target) ||
  !["sync", "build", "release"].includes(action)
)
  throw new Error(
    "Usage: node scripts/android.mjs local|production sync|build|release",
  );
if (action === "release" && target !== "production")
  throw new Error("Release builds must use production HTTPS configuration.");
const mode = `android-${target}`;
const env = {
  ...loadEnv(mode, root, ""),
  ...process.env,
  CIVICFLOW_ANDROID_LOCAL: String(target === "local"),
};
const url = env.VITE_API_URL;
let parsed;
try {
  parsed = new URL(url);
} catch {
  throw new Error(
    `Set VITE_API_URL in frontend/.env.${mode}.local to a full API address ending in /api.`,
  );
}
if (
  !["http:", "https:"].includes(parsed.protocol) ||
  !parsed.pathname.endsWith("/api") ||
  parsed.search ||
  parsed.hash ||
  parsed.username ||
  parsed.password
)
  throw new Error(
    "VITE_API_URL must be an HTTP(S) address ending in /api without credentials or query parameters.",
  );
if (
  target === "production" &&
  (parsed.protocol !== "https:" ||
    ["localhost", "127.0.0.1", "10.0.2.2"].includes(parsed.hostname) ||
    parsed.hostname.endsWith(".example"))
)
  throw new Error(
    "Production Android requires a reachable HTTPS API in .env.android-production.local.",
  );
const executable = (name) => resolve(root, "node_modules", ...name.split("/"));
function node(script, args) {
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: root,
    env,
    stdio: "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status || 1);
}
node(executable("typescript/bin/tsc"), ["-b"]);
node(executable("vite/bin/vite.js"), ["build", "--mode", mode]);
node(executable("@capacitor/cli/bin/capacitor"), ["sync", "android"]);
writeFileSync(
  resolve(root, "android/civicflow.local.properties"),
  `# Generated by npm Android scripts. Do not commit.\ncivicflow.cleartext=${target === "local"}\n`,
);
console.log(`Android assets synchronized for ${url}.`);
if (action !== "sync") {
  const windows = process.platform === "win32";
  const wrapper = resolve(root, "android", windows ? "gradlew.bat" : "gradlew");
  if (!windows) chmodSync(wrapper, 0o755);
  if (
    !process.env.ANDROID_HOME &&
    !process.env.ANDROID_SDK_ROOT &&
    !existsSync(resolve(root, "android/local.properties"))
  )
    console.warn(
      "Android SDK not configured. Set ANDROID_HOME or open this project in Android Studio first.",
    );
  const result = spawnSync(
    windows ? `"${wrapper}"` : wrapper,
    [action === "release" ? "bundleRelease" : "assembleDebug"],
    { cwd: resolve(root, "android"), stdio: "inherit", env, shell: windows },
  );
  if (result.error) throw result.error;
  process.exit(result.status || 0);
}
